#!/usr/bin/env node
/**
 * MUGA: sync-wrappers — vendor caps-spec/wrappers.json into muga.
 *
 * Mirrors the cleaner-bundle.js / generate-dnr-rules.mjs pattern: the
 * normative artifact lives in caps-spec; muga ships a vendored snapshot
 * verified at sync time and pinned by a unit-test invariant.
 *
 * Source of truth: caps-spec repo. Override the source path with
 * CAPS_SPEC_DIR (default: ../caps-spec relative to this repo).
 *
 * Steps:
 *   1. Read wrappers.json + wrappers.json.sig + worker-pubkey.txt from source
 *   2. Verify Ed25519 signature against pinned pubkey (fail-closed)
 *   3. Copy verified files into src/vendor/caps-spec/
 *   4. Regenerate src/vendor/caps-spec/wrappers.data.js from the JSON so
 *      wrapper-engine.js can import a pure ESM module without depending on
 *      import attributes (`with { type: "json" }`)
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { webcrypto } from "node:crypto";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const VENDOR_DIR = join(REPO_ROOT, "src", "vendor", "caps-spec");
const SOURCE_DIR = process.env.CAPS_SPEC_DIR
  ? resolve(process.env.CAPS_SPEC_DIR)
  : resolve(REPO_ROOT, "..", "caps-spec");

function readSource(name) {
  const path = join(SOURCE_DIR, name);
  try {
    return readFileSync(path);
  } catch (err) {
    throw new Error(
      `sync-wrappers: cannot read ${path}. Set CAPS_SPEC_DIR to the caps-spec checkout. (${err.message})`,
    );
  }
}

/**
 * Normalize CRLF -> LF.
 *
 * The wrappers.json signature in caps-spec is computed over the LF-normalized
 * git blob (.github/workflows/wrappers.yml runs on Linux). On a Windows
 * checkout with core.autocrlf=true the file's working-tree bytes are CRLF, so
 * a verbatim verify against the working-tree bytes would always fail. We
 * normalize on read and vendor the LF form so:
 *   - signature verifies cross-platform identically to CI
 *   - the vendored bytes match what was signed (one source of truth)
 */
function normalizeLf(buf) {
  // Strip every 0x0D that immediately precedes a 0x0A; leave standalone
  // 0x0D alone (none expected in JSON / base64 sig / pubkey, but cheap to be
  // conservative).
  const out = [];
  for (let i = 0; i < buf.length; i++) {
    if (buf[i] === 0x0d && buf[i + 1] === 0x0a) continue;
    out.push(buf[i]);
  }
  return Buffer.from(out);
}

function decodeBase64(str) {
  return Buffer.from(str.trim(), "base64");
}

async function importEd25519PublicKey(rawBytes) {
  // Ed25519 raw public keys are 32 bytes per RFC 8032. WebCrypto's "raw"
  // import for Ed25519 expects the 32-byte public key directly.
  return webcrypto.subtle.importKey(
    "raw",
    rawBytes,
    { name: "Ed25519" },
    false,
    ["verify"],
  );
}

async function verifySignature(payload, sigBytes, pubKey) {
  return webcrypto.subtle.verify("Ed25519", pubKey, sigBytes, payload);
}

function generateDataModule(json) {
  const banner = [
    "// AUTO-GENERATED by scripts/sync-wrappers.mjs from src/vendor/caps-spec/wrappers.json.",
    "// DO NOT EDIT BY HAND. Run `npm run sync:wrappers` to refresh.",
    "// Source of truth: yocreoquesi/caps-spec (Ed25519-signed normative artifact).",
    "",
  ].join("\n");
  const body = `export const WRAPPERS_RAW = ${JSON.stringify(json, null, 2)};\n`;
  return `${banner}${body}`;
}

async function main() {
  console.log(`sync-wrappers: source = ${SOURCE_DIR}`);

  const wrappersBuf = normalizeLf(readSource("wrappers.json"));
  const sigBuf = normalizeLf(readSource("wrappers.json.sig"));
  const pubkeyBuf = normalizeLf(readSource("worker-pubkey.txt"));

  const sigBytes = decodeBase64(sigBuf.toString("utf8"));
  const pubBytes = decodeBase64(pubkeyBuf.toString("utf8"));

  if (pubBytes.length !== 32) {
    throw new Error(
      `sync-wrappers: pinned pubkey must be 32 bytes (Ed25519 raw); got ${pubBytes.length}`,
    );
  }
  if (sigBytes.length !== 64) {
    throw new Error(
      `sync-wrappers: signature must be 64 bytes (Ed25519); got ${sigBytes.length}`,
    );
  }

  const pubKey = await importEd25519PublicKey(pubBytes);
  const ok = await verifySignature(wrappersBuf, sigBytes, pubKey);
  if (!ok) {
    throw new Error(
      "sync-wrappers: SIGNATURE VERIFICATION FAILED. Refusing to vendor an unsigned/tampered wrappers.json.",
    );
  }
  console.log("sync-wrappers: Ed25519 signature OK");

  let parsed;
  try {
    parsed = JSON.parse(wrappersBuf.toString("utf8"));
  } catch (err) {
    throw new Error(`sync-wrappers: wrappers.json is not valid JSON: ${err.message}`);
  }
  if (!Array.isArray(parsed)) {
    throw new Error("sync-wrappers: wrappers.json root must be an array");
  }

  writeFileSync(join(VENDOR_DIR, "wrappers.json"), wrappersBuf);
  writeFileSync(join(VENDOR_DIR, "wrappers.json.sig"), sigBuf);
  writeFileSync(join(VENDOR_DIR, "worker-pubkey.txt"), pubkeyBuf);
  writeFileSync(
    join(VENDOR_DIR, "wrappers.data.js"),
    generateDataModule(parsed),
  );

  console.log(
    `sync-wrappers: vendored ${parsed.length} entries → src/vendor/caps-spec/`,
  );
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
