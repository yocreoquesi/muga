#!/usr/bin/env node
/**
 * MUGA: sync-affiliate-manifest — vendor caps-spec/manifest.json into muga.
 *
 * Sibling of scripts/sync-wrappers.mjs. The wrappers script handles the
 * `network-redirect` half of caps-spec/manifest.json (vendored as a
 * separate `wrappers.json` file in the spec repo). This script handles
 * the OTHER half: the `direct-injection` programs that carry creator
 * affiliate tags MUGA must preserve.
 *
 * Source of truth: caps-spec repo. Override the source path with
 * CAPS_SPEC_DIR (default: ../caps-spec relative to this repo).
 *
 * Steps:
 *   1. Read manifest.json (and optional manifest.json.sig + signer-pubkey.txt)
 *      from source.
 *   2. Verify Ed25519 signature when a signature is available, fail-closed.
 *      In the interim before caps-spec ships its signing pipeline, this
 *      script accepts `--allow-unsigned` to vendor the unsigned manifest
 *      with a loud notice. Tracked for follow-up.
 *   3. Filter `programs` to `programType === "direct-injection"` — the
 *      `network-redirect` half is vendored separately as `wrappers.json`.
 *   4. Write src/vendor/caps-spec/manifest.json (LF-normalized, the verified
 *      bytes) and src/vendor/caps-spec/manifest.data.js (a pure ESM module
 *      exporting CAPS_DIRECT_INJECTION_PROGRAMS) so affiliates.js can import
 *      without `with { type: "json" }`.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { webcrypto } from "node:crypto";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const VENDOR_DIR = join(REPO_ROOT, "src", "vendor", "caps-spec");
const SOURCE_DIR = process.env.CAPS_SPEC_DIR
  ? resolve(process.env.CAPS_SPEC_DIR)
  : resolve(REPO_ROOT, "..", "caps-spec");

const ALLOW_UNSIGNED = process.argv.includes("--allow-unsigned");

function readSource(name, { optional = false } = {}) {
  const path = join(SOURCE_DIR, name);
  try {
    return readFileSync(path);
  } catch (err) {
    if (optional) return null;
    throw new Error(
      `sync-affiliate-manifest: cannot read ${path}. Set CAPS_SPEC_DIR to the caps-spec checkout. (${err.message})`,
    );
  }
}

/**
 * Normalize CRLF -> LF.
 *
 * Same rationale as sync-wrappers.mjs: the signature in caps-spec is
 * computed over LF-normalized bytes (the spec's CI runs on Linux). On a
 * Windows checkout with core.autocrlf=true the working-tree bytes are
 * CRLF, so a verbatim verify against the working-tree bytes would always
 * fail. We normalize on read and vendor the LF form so signature verifies
 * cross-platform identically to CI and the vendored bytes match what was
 * signed.
 */
function normalizeLf(buf) {
  const out = [];
  for (let i = 0; i < buf.length; i++) {
    if (buf[i] === 0x0d && buf[i + 1] === 0x0a) continue;
    out.push(buf[i]);
  }
  return Buffer.from(out);
}

function decodeBase64(str) {
  return Buffer.from(str.trim(), "base64");
}

async function importEd25519PublicKey(rawBytes) {
  return webcrypto.subtle.importKey(
    "raw",
    rawBytes,
    { name: "Ed25519" },
    false,
    ["verify"],
  );
}

async function verifySignature(payload, sigBytes, pubKey) {
  return webcrypto.subtle.verify("Ed25519", pubKey, sigBytes, payload);
}

function generateDataModule(programs) {
  const banner = [
    "// AUTO-GENERATED by scripts/sync-affiliate-manifest.mjs from src/vendor/caps-spec/manifest.json.",
    "// DO NOT EDIT BY HAND. Run `npm run sync:manifest` to refresh.",
    "// Source of truth: yocreoquesi/caps-spec (manifest.json, direct-injection programs).",
    "",
  ].join("\n");
  const body = `export const CAPS_DIRECT_INJECTION_PROGRAMS = ${JSON.stringify(programs, null, 2)};\n`;
  return `${banner}${body}`;
}

async function main() {
  console.log(`sync-affiliate-manifest: source = ${SOURCE_DIR}`);
  if (ALLOW_UNSIGNED) {
    console.log("sync-affiliate-manifest: --allow-unsigned set");
  }

  const manifestBuf = normalizeLf(readSource("manifest.json"));

  // Look for a detached signature (mirrors wrappers.json.sig). If absent,
  // fall back to checking the in-band `signature` field inside the JSON
  // itself. If neither is present, require --allow-unsigned.
  const sigBuf = readSource("manifest.json.sig", { optional: true });
  const pubkeyBuf = readSource("signer-pubkey.txt", { optional: true });

  let parsed;
  try {
    parsed = JSON.parse(manifestBuf.toString("utf8"));
  } catch (err) {
    throw new Error(`sync-affiliate-manifest: manifest.json is not valid JSON: ${err.message}`);
  }
  if (!parsed || !Array.isArray(parsed.programs)) {
    throw new Error("sync-affiliate-manifest: manifest.json must have a `programs` array at the root");
  }

  const detachedAvailable = sigBuf != null && pubkeyBuf != null;
  const inBandAvailable =
    parsed.signature != null && parsed.signer_pubkey != null;

  if (detachedAvailable) {
    const sigBytes = decodeBase64(normalizeLf(sigBuf).toString("utf8"));
    const pubBytes = decodeBase64(normalizeLf(pubkeyBuf).toString("utf8"));
    if (pubBytes.length !== 32) {
      throw new Error(
        `sync-affiliate-manifest: pinned pubkey must be 32 bytes (Ed25519 raw); got ${pubBytes.length}`,
      );
    }
    if (sigBytes.length !== 64) {
      throw new Error(
        `sync-affiliate-manifest: signature must be 64 bytes (Ed25519); got ${sigBytes.length}`,
      );
    }
    const pubKey = await importEd25519PublicKey(pubBytes);
    const ok = await verifySignature(manifestBuf, sigBytes, pubKey);
    if (!ok) {
      throw new Error(
        "sync-affiliate-manifest: SIGNATURE VERIFICATION FAILED (detached). Refusing to vendor a tampered manifest.",
      );
    }
    console.log("sync-affiliate-manifest: Ed25519 detached signature OK");
  } else if (inBandAvailable) {
    // The in-band signing convention: the `signature` field is computed
    // over a canonical form of the manifest where `signature` itself is
    // null (or empty string). Verifying requires re-canonicalizing here
    // — left for the follow-up that lands in lockstep with caps-spec's
    // signing pipeline. For now, refuse to load an in-band-signed
    // manifest without explicit override.
    if (!ALLOW_UNSIGNED) {
      throw new Error(
        "sync-affiliate-manifest: in-band signature present but verifier not implemented yet. " +
        "Pass --allow-unsigned to vendor anyway, or wait for the matching verifier to land.",
      );
    }
    console.log("sync-affiliate-manifest: WARNING — in-band signature present but skipped (--allow-unsigned)");
  } else {
    if (!ALLOW_UNSIGNED) {
      throw new Error(
        "sync-affiliate-manifest: no signature available (manifest.json.sig missing AND in-band signature null). " +
        "Pass --allow-unsigned to vendor anyway. Once caps-spec ships its signing pipeline, drop the flag.",
      );
    }
    console.log("sync-affiliate-manifest: WARNING — vendoring unsigned manifest (--allow-unsigned)");
  }

  const direct = parsed.programs.filter(
    (p) => p && p.programType === "direct-injection",
  );
  if (direct.length === 0) {
    throw new Error("sync-affiliate-manifest: no direct-injection programs found in manifest.json");
  }

  // Drop fields MUGA does not consume to keep the vendored module small.
  // Keep the canonical caps-spec fields plus `references` for transparency
  // (the references field carries the archived URLs the program identity
  // was derived from).
  const projected = direct.map((p) => ({
    id: p.id,
    name: p.name,
    programType: p.programType,
    domains: p.domains,
    param: p.param,
    valueShape: p.valueShape,
    notes: p.notes,
    references: p.references,
  }));

  writeFileSync(join(VENDOR_DIR, "manifest.json"), manifestBuf);
  if (sigBuf) writeFileSync(join(VENDOR_DIR, "manifest.json.sig"), normalizeLf(sigBuf));
  if (pubkeyBuf && !existsSync(join(VENDOR_DIR, "signer-pubkey.txt"))) {
    writeFileSync(join(VENDOR_DIR, "signer-pubkey.txt"), normalizeLf(pubkeyBuf));
  }
  writeFileSync(join(VENDOR_DIR, "manifest.data.js"), generateDataModule(projected));

  console.log(
    `sync-affiliate-manifest: vendored ${projected.length} direct-injection programs → src/vendor/caps-spec/`,
  );
  for (const p of projected) {
    console.log(`  ${p.id}  param=${p.param}  domains=${p.domains.length}`);
  }
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
